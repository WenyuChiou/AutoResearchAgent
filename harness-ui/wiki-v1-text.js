const V1_MARK = '⁠'; // word joiner: zero width, appended to every text that fell back to Simplified
const V1_CJK = /[　-〿一-鿿＀-￯]/;

// Same language source as rl() and v9-route-language.js: the language of the first app (apps[0].lang: zh, en or tw).
function v1Locale() {
 const lang = typeof apps !== 'undefined' ? apps[0]?.lang : undefined;
 return lang === 'en' || lang === 'tw' ? lang : 'zh';
}
// Date text follows the interface language.
function v1DateLocale() {
 return ({zh:'zh-CN', en:'en-US', tw:'zh-TW'})[v1Locale()];
}
// All pages (home, global pages, Stage pages, drawer) use the V1 design in all three languages.
function v1Lang(app) {
 return !!app && (app.lang === 'zh' || app.lang === 'en' || app.lang === 'tw');
}
function v1StageLang(app) {
 return v1Lang(app);
}

const v1TextWarned = new Set();
function v1t(key, vars) {
 if (typeof key !== 'string' || !key) return key;
 const lang = v1Locale();
 let text = key, fell = false;
 if (lang !== 'zh' && V1_CJK.test(key)) {
  const value = Object.hasOwn(v1Text, key) ? v1Text[key][lang] : '';
  if (typeof value === 'string' && value.trim()) text = value;
  else {
   fell = true;
   if (!v1TextWarned.has(lang + '|' + key)) {
    v1TextWarned.add(lang + '|' + key);
    if (typeof console !== 'undefined') console.warn('v1t: no ' + lang + ' text for', key);
   }
  }
 }
 if (vars) text = text.replace(/\{(\w+)\}/g, (whole, name) => Object.hasOwn(vars, name) ? String(vars[name]) : whole);
 return fell ? text + V1_MARK : text;
}

// Top-level tables that hold Simplified text: reading a string out of them goes through v1t at the moment of use,
// so the table follows the current language. Arrays and plain objects are wrapped deeply; other objects pass through.
function v1Lazy(value) {
 if (value === null || typeof value !== 'object') return value;
 if (!Array.isArray(value) && Object.getPrototypeOf(value) !== Object.prototype) return value;
 return new Proxy(value, {
  get(target, prop, receiver) {
   const item = Reflect.get(target, prop, receiver);
   if (typeof prop === 'symbol') return item;
   if (typeof item === 'string') return v1t(item);
   return typeof item === 'object' ? v1Lazy(item) : item;
  }
 });
}

